"""Initial tables of the 8-symbol coefficient alphabet (format v3 flag MULE_COEF_A8): the coef
stream (96 contexts x 8 symbols, escape at 7) and the cesc stream (16 x 16, Exp-Golomb orders of
mag - 7), counted on the `train` traces (eval/ctx_lab.py, default settings), into
core/init_cdf_a8.h."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "py"), os.path.join(ROOT, "eval")]
import ctx_lab  # noqa: E402


def main():
    """Writes core/init_cdf_a8.h: the 8-symbol coefficient and escape CDFs trained on the train
    traces (eval/ctx_lab.py)."""
    coef, cesc = ctx_lab._alpha_bits(ctx_lab.ensure("train"), 7)
    def arr(name, a):
        v = ", ".join(str(int(x)) for x in a.ravel())
        return f"static const uint16_t {name}[{a.size}] = {{{v}}};\n"
    with open(os.path.join(ROOT, "core", "init_cdf_a8.h"), "w") as f:
        f.write("/* Generated by tools/gen_init_a8.py from the train traces: do not edit. */\n")
        f.write("#ifndef MULE_INIT_CDF_A8_H\n#define MULE_INIT_CDF_A8_H\n#include <stdint.h>\n\n")
        f.write(arr("mule_init_coef8", coef))
        f.write(arr("mule_init_cesc8", cesc))
        f.write("\n#endif\n")
    print("core/init_cdf_a8.h:", coef.shape, cesc.shape)


if __name__ == "__main__":
    main()
