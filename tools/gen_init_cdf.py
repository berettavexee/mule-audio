"""Generates core/init_cdf.h from py/mule/init_cdf.npz (the trained initial CDFs): the decoder's
ROM tables. Streams absent from the .npz start uniform (NULL)."""
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STREAMS = ["btype", "alpha", "stereo", "energy", "alloc", "amode", "cesc", "coef", "eaesc"]
NSYMS = [2, 4, 2, 16, 16, 2, 16, 16, 16]
NCTX = [1, 1, 3, 9, 6, 1, 16, 96, 1]
TABLE_ID = 2                # MULEHead byte 19: identifies this set of initial CDFs (2: v2, TCQ)


def main(npz=os.path.join(ROOT, "py", "mule", "init_cdf.npz"),
         out=os.path.join(ROOT, "core", "init_cdf.h")):
    tabs = dict(np.load(npz)) if os.path.exists(npz) else {}
    lines = ["/* Generated by tools/gen_init_cdf.py from py/mule/init_cdf.npz: do not edit. */",
             "#ifndef MULE_INIT_CDF_H", "#define MULE_INIT_CDF_H", "#include <stddef.h>",
             "#include <stdint.h>", ""]
    ptrs = []
    for name, n, c in zip(STREAMS, NSYMS, NCTX):
        t = tabs.get(name)
        if t is None or t.shape != (c, n + 1):
            ptrs.append("NULL")
            continue
        vals = ", ".join(str(int(v)) for v in t.reshape(-1))
        lines.append(f"static const uint16_t mule_init_{name}[{c * (n + 1)}] = {{{vals}}};")
        ptrs.append(f"mule_init_{name}")
    lines += ["", f"#define MULE_INIT_CDF_ID {TABLE_ID}",
              "static const uint16_t *const mule_init_cdf[] = {" + ", ".join(ptrs) + "};",
              "", "#endif", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"{out}: {sum(p != 'NULL' for p in ptrs)}/{len(ptrs)} streams trained")


if __name__ == "__main__":
    main(*sys.argv[1:])
