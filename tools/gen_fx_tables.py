"""Generates core/fx_tables.h: the fixed-point decoder's constant tables (no libm on core B).
  - slopes of the Vorbis window for 1024 and 128 (Q31, rising)
  - IMDCT rotations w[m] = exp(-2 i pi (m + 1/8) / n) for n = 2048 and 256 (Q31 cos, sin), the
    definition of the firmware's fft_tw2048 / fft_tw256 (hififft.c), so HIFIACC can be used as is
  - FFT twiddles exp(-2 i pi k / 512), k < 256 (Q31; the 64-point FFT takes every 8th)
  - gains sqrt(2 / M) for M = 1024 and 128, 1 / sqrt(2), 2^(i/4) (Q31 / Q30)"""
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
Q31 = 2 ** 31


def q31(v):
    return np.clip(np.round(np.asarray(v) * Q31), -Q31, Q31 - 1).astype(np.int64)


def arr(name, vals, per=8, ctype="int32_t"):
    vals = [int(v) for v in np.asarray(vals).reshape(-1)]
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def slope(s):
    i = np.arange(s) + 0.5
    return np.sin(0.5 * np.pi * np.sin(0.5 * np.pi * i / s) ** 2)


def main(out=os.path.join(ROOT, "core", "fx_tables.h")):
    parts = ["/* Generated by tools/gen_fx_tables.py: do not edit. */", "#ifndef MULE_FX_TABLES_H",
             "#define MULE_FX_TABLES_H", "#include <stdint.h>", ""]
    parts.append(arr("fx_slope1024", q31(slope(1024))))
    parts.append(arr("fx_slope128", q31(slope(128))))
    for n in (2048, 256):
        th = 2 * np.pi * (np.arange(n // 4) + 1 / 8) / n
        parts.append(arr(f"fx_w{n}", np.stack([q31(np.cos(th)), q31(np.sin(th))], 1)))
    k = np.arange(256)
    parts.append(arr("fx_fft_tw", np.stack([q31(np.cos(2 * np.pi * k / 512)),
                                            q31(-np.sin(2 * np.pi * k / 512))], 1)))
    parts.append(f"#define FX_G1024 {int(q31(np.sqrt(2 / 1024)))}\n#define FX_G128 {int(q31(np.sqrt(2 / 128)))}\n"
                 f"#define FX_INVSQRT2 {int(q31(1 / np.sqrt(2)))}\n")
    parts.append(arr("fx_pow4_q30", np.round(2 ** 30 * 2 ** (np.arange(4) / 4)).astype(np.int64), ctype="int64_t"))
    parts.append("#endif\n")
    with open(out, "w") as f:
        f.write("\n".join(parts))
    print(out)


if __name__ == "__main__":
    main()
